"""Copy freely licensed Lichess themes. Usage: python3 scripts/import-themes.py path/to/lila"""
import json, re, shutil, subprocess, sys
from pathlib import Path

lila = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
copying = (lila / 'COPYING.md').read_text()
# no license, or "freeware" / restricted terms that don't clearly allow redistribution
SKIP = {'alpha', 'chess7', 'companion', 'leipzig', 'reillycraig', 'riohacha', 'shahi-ivory-brown'}

def credit(path):
    for line in copying.splitlines():
        cells = [c.strip() for c in line.split('|')]
        if len(cells) >= 3 and path.lower() in cells[0].lower().replace(',', ' ').split():
            return f'{cells[1]}, {cells[2]}'
    return 'lila authors, AGPLv3+ (lila default)'

pieces, credits = [], []
for d in sorted((lila / 'public/piece').iterdir()):
    if not d.is_dir() or d.name in SKIP:
        continue
    shutil.copytree(d, root / 'public/pieces' / d.name, dirs_exist_ok=True)
    ext = 'webp' if any(d.glob('*.webp')) else 'svg'
    mono = not (d / f'wP.{ext}').exists()
    pieces.append({'name': d.name, 'ext': ext, 'mono': mono})
    credits.append(f'- pieces/{d.name}: {credit("public/piece/" + d.name)}')

boards = []
source = lila / 'public/images/board'
(root / 'public/boards').mkdir(parents=True, exist_ok=True)
for f in sorted([*source.glob('*.png'), *source.glob('*.jpg'), *source.glob('svg/*.svg')]):
    if re.search(r'\.(thumbnail|orig|current-premove|last-move|move-dest|selected)\.', f.name):
        continue
    shutil.copy(f, root / 'public/boards' / f.name)
    boards.append({'name': f.stem, 'file': f.name})
    rel = f.relative_to(lila).as_posix()
    own = credit(rel)
    credits.append(f'- boards/{f.name}: ' + (own if 'default' not in own else 'lila authors and pirouetti, AGPLv3+'))

commit = subprocess.run(['git', '-C', str(lila), 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
(root / 'public/CREDITS.md').write_text(
    f'# Theme credits\n\nFrom https://github.com/lichess-org/lila at {commit}\n\n' + '\n'.join(credits) + '\n')
(root / 'src/themes.gen.ts').write_text(
    '// generated by scripts/import-themes.py\n'
    f'export const PIECES = {json.dumps(pieces)};\n'
    f'export const BOARDS = {json.dumps(boards)};\n')
print(len(pieces), 'piece sets', len(boards), 'boards')
